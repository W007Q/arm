"""生成独立的乒乓球拍仿真模型。

该模块从机械臂的 canonical MuJoCo XML 和集中配置生成派生文件，原有
抓取模型不会被修改。生成结果包含六轴机械臂、球拍、自由六自由度乒乓球、
地面、相机和接触参数；`1d` 与 `3d` 只表示控制任务入口，物理模型都允许
球在三个平移和三个旋转自由度上运动。
"""
from __future__ import annotations

import math
import xml.etree.ElementTree as ET

import numpy as np
from scipy.spatial.transform import Rotation

from .parameters import ARM_JOINTS, hardware_profile


def vec(values):
    """把数值序列编码成 MuJoCo XML 使用的空格分隔字符串。"""
    return " ".join(format(float(v), ".15g") for v in values)


def serialize(root):
    """格式化 XML，并标记文件由同步脚本生成，避免手工编辑派生文件。"""
    ET.indent(root, space="  ")
    return '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/sync_robot_parameters.py; edit config/pingpong.yaml. -->\n' + ET.tostring(root, encoding="unicode") + "\n"


def validate_config(c):
    """在生成派生模型前检查物理、控制、视觉和标定配置。"""
    # 这些参数必须为有限正数，否则会生成无法积分或无法控制的模型。
    for section, keys in {
        "paddle": ("radius_m", "thickness_m", "blade_mass_kg", "handle_length_m", "handle_radius_m", "handle_mass_kg", "adapter_radius_m", "adapter_mass_kg"),
        "ball": ("radius_m", "mass_kg", "contact_time_s", "contact_damping_ratio", "contact_width_m", "spin_decay_time_s"),
        "scene": ("timestep_s", "gravity_m_s2", "target_apex_m"),
        "control": ("policy_hz", "servo_hz", "stroke_m", "nominal_restitution", "residual_speed_m_s", "max_paddle_speed_m_s", "max_paddle_acceleration_m_s2", "max_contact_s", "actuator_time_constant_s", "xy_tracking_limit_m", "paddle_tilt_limit_rad", "paddle_tilt_rate_limit_rad_s", "paddle_tilt_acceleration_limit_rad_s2", "xy_tracking_gain_s", "tilt_tracking_time_s", "joint_target_acceleration_rad_s2"),
        "experiment": ("episode_s", "success_bounces"),
    }.items():
        for key in keys:
            value = float(c[section][key])
            if not math.isfinite(value) or value <= 0:
                raise ValueError(f"pingpong.{section}.{key} must be positive and finite")
    # 仿真步长要能整除控制周期，且伺服频率必须是策略频率的整数倍。
    dt = c["scene"]["timestep_s"]
    for rate in (c["control"]["policy_hz"], c["control"]["servo_hz"]):
        if not np.isclose(1 / (rate * dt), round(1 / (rate * dt))) or rate * dt > 1:
            raise ValueError("pingpong timestep must divide policy/servo periods")
    if c["control"]["servo_hz"] % c["control"]["policy_hz"]:
        raise ValueError("pingpong servo_hz must be a multiple of policy_hz")
    if c["ball"]["inertia_model"] != "thin_shell":
        raise ValueError("pingpong ball.inertia_model must be thin_shell")
    if c["ball"]["contact_time_s"] < 2 * dt:
        raise ValueError("pingpong contact time constant must be at least twice timestep")
    if c["control"]["nominal_restitution"] > 1:
        raise ValueError("pingpong nominal_restitution cannot add passive collision energy")
    # 摩擦、空气阻力和跟踪增益允许为零，但不能是负数或 NaN。
    for section, keys in {
        "ball": ("sliding_friction", "torsional_friction_m", "rolling_friction_m", "drag_coefficient", "air_density_kg_m3", "magnus_lift_slope", "magnus_lift_max"),
        "control": ("actuator_delay_s", "lateral_position_gain_rad_m", "lateral_velocity_gain_rad_s_m", "xy_tracking_damping", "tracking_lookahead_s"),
    }.items():
        for key in keys:
            value = float(c[section][key])
            if not math.isfinite(value) or value < 0:
                raise ValueError(f"pingpong.{section}.{key} must be nonnegative and finite")
    if np.asarray(c["scene"]["wind_velocity_m_s"]).shape != (3,) or not np.all(np.isfinite(c["scene"]["wind_velocity_m_s"])):
        raise ValueError("pingpong.scene.wind_velocity_m_s must be a finite XYZ vector")
    for key, length in (("cartesian_speed_limit_m_s", 3), ("cartesian_acceleration_limit_m_s2", 3),
                        ("residual_cartesian_speed_m_s", 3), ("residual_tilt_rate_rad_s", 2)):
        values = np.asarray(c["control"][key], dtype=float)
        if values.shape != (length,) or not np.isfinite(values).all() or np.any(values <= 0):
            raise ValueError(f"pingpong.control.{key} must have {length} finite positive entries")
    if c["control"]["tracking_lookahead_s"] > .30:
        raise ValueError("pingpong.control.tracking_lookahead_s must not exceed .30")
    for camera in c["cameras"].values():
        if not 0 < camera["fovy_deg"] < 180:
            raise ValueError("pingpong camera fovy_deg must be inside (0, 180)")
        if np.linalg.norm(np.subtract(camera["position_m"], camera["look_at_m"])) < 1e-6:
            raise ValueError("pingpong camera position equals look_at")
    # 视觉输入固定为两个不同的标定相机，控制器不得退回球的真值状态。
    perception = c["perception"]
    if len(perception["camera_names"]) != 2 or len(set(perception["camera_names"])) != 2:
        raise ValueError("pingpong perception requires two distinct calibrated cameras")
    for name in perception["camera_names"]:
        if name not in c["cameras"]:
            raise ValueError(f"pingpong perception camera {name} is missing")
    for key in ("width", "height", "fps", "max_age_s", "tracking_timeout_s"):
        value = float(perception[key])
        if not math.isfinite(value) or value <= 0:
            raise ValueError(f"pingpong.perception.{key} must be positive and finite")
    for key in ("latency_s", "latency_jitter_s", "exposure_s", "image_noise_std", "blur_sigma_px", "centroid_noise_std_px", "calibration_position_std_m", "calibration_rotation_std_deg", "calibration_focal_relative_std"):
        value = float(perception[key])
        if not math.isfinite(value) or value < 0:
            raise ValueError(f"pingpong.perception.{key} must be nonnegative and finite")
    if perception["exposure_s"] > 1 / perception["fps"]:
        raise ValueError("pingpong perception exposure cannot exceed camera period")
    if not 0 <= perception["dropout_probability"] <= 1:
        raise ValueError("pingpong perception dropout_probability must be inside [0, 1]")
    if c["calibration"]["status"] not in ("unmeasured", "measured"):
        raise ValueError("pingpong calibration.status must be unmeasured or measured")
    if c["calibration"]["status"] == "measured":
        calibration = c["calibration"]
        if not calibration["ball_id"] or not calibration["paddle_id"] or len(calibration["measurements"]) < 3:
            raise ValueError("pingpong measured calibration needs ball/paddle IDs and at least three real drop measurements")
        for sample in calibration["measurements"]:
            for key in ("drop_height_m", "rebound_height_m", "contact_duration_s", "incoming_speed_m_s", "outgoing_speed_m_s"):
                value = float(sample[key])
                if not math.isfinite(value) or value <= 0:
                    raise ValueError(f"pingpong measured calibration {key} must be positive and finite")
            if sample["outgoing_speed_m_s"] > sample["incoming_speed_m_s"]:
                raise ValueError("pingpong passive fixed-paddle calibration cannot add energy")
    if c["ball"]["radius_m"] >= c["paddle"]["radius_m"]:
        raise ValueError("pingpong ball must fit on paddle")


def camera_axes(camera):
    """根据相机位置和注视点计算 MuJoCo `xyaxes` 参数。"""
    z = np.subtract(camera["position_m"], camera["look_at_m"])
    z = z / np.linalg.norm(z)
    x = np.cross([0., 0., 1.], z)
    if np.linalg.norm(x) < 1e-6:
        x = np.cross([0., 1., 0.], z)
    x /= np.linalg.norm(x)
    return vec(np.r_[x, np.cross(z, x)])


def derived_pingpong_files(robot_text, config, hardware, limits):
    """生成球拍机械臂 XML 以及独立的 1D/3D 场景 XML。

    输入机械臂文本只在内存中解析并复制；输出写入由调用方负责，因此不会
    破坏 `grasp_scene.xml` 等原始模型。
    """
    validate_config(config)
    robot = ET.fromstring(robot_text)
    robot.set("model", "rebotarm_six_axis_paddle")
    # 用球拍替换末端夹爪，同时保留原机械臂的六个关节和 CAD 外观。
    wrist = robot.find(".//body[@name='link6']")
    hand = wrist.find("body[@name='gripper_end']")
    if hand is None:
        raise ValueError("source robot must contain link6/gripper_end")
    wrist.remove(hand)
    for tag in ("keyframe", "equality"):
        element = robot.find(tag)
        if element is not None:
            robot.remove(element)
    actuators = robot.find("actuator")
    profile = {j["name"]: j for j in hardware_profile(hardware)["joints"]}
    for actuator in list(actuators):
        name = actuator.get("joint")
        if name not in ARM_JOINTS:
            actuators.remove(actuator)
            continue
        motor = hardware["motor_catalog"][profile[name]["model"]]
        torque = min(float(limits[name]["effort"]), float(motor["peak"]))
        actuator.set("ctrlrange", vec([-torque, torque]))
        joint = robot.find(f".//joint[@name='{name}']")
        joint.set("armature", str(float(motor["rotor_inertia"]) * float(motor["gear"]) ** 2))
        joint.set("damping", str(motor["friction_viscous"]))
    # 保留 CAD 外观；用碰撞掩码打开球/地面接触，并沿用原模型的自碰撞策略。
    # 这些代理几何仍需在真机迁移前单独验证，不能当作完整自碰撞检测。
    for geom in robot.findall(".//geom"):
        if geom.get("contype", "1") != "0":
            geom.set("contype", "2")
            geom.set("conaffinity", "1")
    used = {g.get("mesh") for g in robot.findall(".//geom") if g.get("mesh")}
    assets = robot.find("asset")
    for mesh in list(assets):
        if mesh.get("name") not in used:
            assets.remove(mesh)
    # 球拍由拍面、手柄和腕部转接件组成，质量直接来自 pingpong.yaml。
    p = config["paddle"]
    quat = Rotation.from_euler("xyz", p["mount_rpy_rad"]).as_quat()[[3, 0, 1, 2]]
    paddle = ET.SubElement(wrist, "body", name="pingpong_paddle", pos=vec(p["mount_xyz_m"]), quat=vec(quat))
    radius, half = p["radius_m"], p["thickness_m"] / 2
    ET.SubElement(paddle, "geom", name="paddle_face", type="cylinder", size=vec([radius, half]), mass=str(p["blade_mass_kg"]), rgba="0.82 0.09 0.07 1", contype="4", conaffinity="1", condim="6")
    ET.SubElement(paddle, "geom", name="paddle_handle", type="capsule", fromto=vec([0, -radius, 0, 0, -radius-p["handle_length_m"], 0]), size=str(p["handle_radius_m"]), mass=str(p["handle_mass_kg"]), rgba="0.52 0.30 0.12 1", contype="2", conaffinity="1")
    wrist_origin = -Rotation.from_euler("xyz", p["mount_rpy_rad"]).as_matrix().T @ p["mount_xyz_m"]
    ET.SubElement(paddle, "geom", name="paddle_adapter", type="capsule", fromto=vec([*wrist_origin, 0, -radius-p["handle_length_m"], 0]), size=str(p["adapter_radius_m"]), mass=str(p["adapter_mass_kg"]), rgba="0.35 0.38 0.40 1", contype="2", conaffinity="1")
    ET.SubElement(paddle, "site", name="paddle_surface", pos=vec([0, 0, half]), size="0.004", rgba="0 1 0 1")
    files = {"robot_pingpong.xml": serialize(robot)}
    for dimension in ("1d", "3d"):
        # 两种场景共用同一套物理；区别只留给控制策略和训练课程使用。
        scene = ET.Element("mujoco", model=f"rebotarm_pingpong_{dimension}")
        ET.SubElement(scene, "include", file="robot_pingpong.xml")
        s, b = config["scene"], config["ball"]
        ET.SubElement(scene, "option", timestep=str(s["timestep_s"]), gravity=vec([0, 0, -s["gravity_m_s2"]]), integrator="implicitfast", solver="Newton", iterations="30", tolerance="1e-9")
        visual = ET.SubElement(scene, "visual")
        ET.SubElement(visual, "global", offwidth="1280", offheight="720")
        world = ET.SubElement(scene, "worldbody")
        ET.SubElement(world, "light", pos="0.3 -0.4 1.8", dir="0 0 -1", diffuse="0.8 0.8 0.8")
        ET.SubElement(world, "geom", name="floor", type="plane", pos=vec([0, 0, s["floor_z_m"]]), size="2 2 0.1", rgba="0.14 0.20 0.24 1", contype="1", conaffinity="7")
        ET.SubElement(world, "geom", name="base_pedestal", type="cylinder", pos="0 0 -0.03", size="0.09 0.03", rgba="0.25 0.28 0.32 1", contype="0", conaffinity="0")
        for name, camera in config["cameras"].items():
            ET.SubElement(world, "camera", name=f"pingpong_{name}", pos=vec(camera["position_m"]), xyaxes=camera_axes(camera), fovy=str(camera["fovy_deg"]))
        xyz = list(s["home_surface_xyz_m"])
        xyz[2] += b["radius_m"] + s["target_apex_m"]
        ball = ET.SubElement(world, "body", name="pingpong_ball", pos=vec(xyz))
        # “1d” 只描述动作课程，不是物理约束；自由球侧飞或掉拍必须真实失败。
        ET.SubElement(ball, "freejoint", name="pingpong_ball_freejoint")
        inertia = (2 / 3) * b["mass_kg"] * b["radius_m"] ** 2
        # 空心薄壳球的转动惯量为 2/3*m*r²，避免把球误当成实心球。
        ET.SubElement(ball, "inertial", pos="0 0 0", mass=str(b["mass_kg"]), diaginertia=vec([inertia] * 3))
        ET.SubElement(ball, "geom", name="ball", type="sphere", size=str(b["radius_m"]), mass=str(b["mass_kg"]), rgba="0.98 0.98 0.98 1", contype="1", conaffinity="7", condim="6", friction=vec([b["sliding_friction"], b["torsional_friction_m"], b["rolling_friction_m"]]))
        contact = ET.SubElement(scene, "contact")
        # 球拍专用接触对覆盖默认求解器参数，便于按实测回弹时间校准。
        ET.SubElement(contact, "pair", geom1="ball", geom2="paddle_face", condim="6", friction=vec([b["sliding_friction"], b["sliding_friction"], b["torsional_friction_m"], b["rolling_friction_m"], b["rolling_friction_m"]]), solref=vec([b["contact_time_s"], b["contact_damping_ratio"]]), solimp=vec([.99, .99, b["contact_width_m"]]))
        files[f"pingpong_{dimension}_scene.xml"] = serialize(scene)
    return files
